const SUPPORTED_LANGS = ['cs', 'sk', 'en'];
let _currentLang = 'cs';

function detectBrowserLanguage() {
  const nav = (navigator.language || navigator.userLanguage || 'cs').toLowerCase();
  const primary = nav.split('-')[0];
  if (primary === 'sk') return 'sk';
  if (primary === 'cs') return 'cs';
  if (primary === 'en') return 'en';
  if (nav.includes('sk')) return 'sk';
  if (nav.includes('cz')) return 'cs';
  return 'en';
}

function initI18n() {
  let stored = null;
  try { stored = localStorage.getItem('naskraj_lang'); } catch {}
  if (stored && SUPPORTED_LANGS.includes(stored)) {
    _currentLang = stored;
  } else {
    _currentLang = detectBrowserLanguage();
    try { localStorage.setItem('naskraj_lang', _currentLang); } catch {}
  }
  try { document.documentElement.lang = _currentLang; } catch {}
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  _currentLang = lang;
  try { localStorage.setItem('naskraj_lang', lang); } catch {}
  try { document.documentElement.lang = lang; } catch {}
  if (typeof renderApp === 'function') renderApp();
}

function getLanguage() { return _currentLang; }

function t(key, params) {
  const lang = TRANSLATIONS[_currentLang] || TRANSLATIONS.cs;
  const parts = String(key).split('.');
  let val = lang;
  let found = true;
  for (const p of parts) {
    if (val && typeof val === 'object' && p in val) {
      val = val[p];
    } else { found = false; break; }
  }
  if (!found || typeof val !== 'string') {
    val = TRANSLATIONS.cs;
    for (const p of parts) {
      if (val && typeof val === 'object' && p in val) val = val[p];
      else return key;
    }
  }
  if (typeof val !== 'string') return key;
  if (params) {
    return val.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : `{${k}}`));
  }
  return val;
}

